// comments are used to explain the code and make it more readable.
// They are ignored by Javascript engine and do not affect the execution of the code.


// There are two types of comments in javascript:

// 1.single line comments: These comments start with two forward slashs (//) and continue until end of the line
// Example:
console.log("This is single-line comment"); // This is a comment

